export function formatNumber(value: number): string {
  if (value % 1 === 0) {
    return new Intl.NumberFormat('fa-IR').format(value);
  }
  return new Intl.NumberFormat('fa-IR', { maximumFractionDigits: 1 }).format(value);
}

export function formatGlasses(value: number): string {
  if (value === 0.5) return 'نصف لیوان';
  if (value === 1) return '۱ لیوان';
  return `${formatNumber(value)} لیوان`;
}

export function formatDate(date: Date, options?: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat('fa-IR-u-ca-persian', options ?? {
    day: 'numeric',
    month: 'long',
  }).format(date);
}

export function formatTime(date: Date): string {
  return new Intl.DateTimeFormat('fa-IR', { hour: '2-digit', minute: '2-digit' }).format(date);
}

export function toEnglishDigits(str: string): string {
  return str
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 1776))
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 1632))
    .replace(/[٫,/]/g, '.');
}

export function localDayKey(date: Date): string {
  const year = date.getFullYear();
  const month = `${date.getMonth() + 1}`.padStart(2, '0');
  const day = `${date.getDate()}`.padStart(2, '0');
  return `${year}-${month}-${day}`;
}

export function relativeTimeFromNow(isoString: string): string {
  const date = new Date(isoString);
  const diffMs = Date.now() - date.getTime();
  const diffMins = Math.floor(diffMs / (60 * 1000));
  
  if (diffMins < 1) return strings.justNow;
  if (diffMins < 60) return `${formatNumber(diffMins)} ${strings.minutesAgo}`;
  const diffHours = Math.floor(diffMins / 60);
  if (diffHours < 24) return `${formatNumber(diffHours)} ${strings.hoursAgo}`;
  return formatDate(date);
}
